function parseRawRows(tableId, rawRows) {
  const result = {};
  for (const raw of rawRows) {
    const [mainBarDia, transverseBarDia, encoded] = raw.split('/');
    if (!mainBarDia || !transverseBarDia || !encoded) {
      throw new TypeError(`Invalid Appendix A3 source row: ${tableId}:${raw}`);
    }
    if (result[mainBarDia]?.[transverseBarDia]) {
      throw new TypeError(
        `Duplicate Appendix A3 source row: ${tableId}:${mainBarDia}:${transverseBarDia}`,
      );
    }

    const starredCoverRule = encoded.startsWith('*');
    const valuesMm = (starredCoverRule ? encoded.slice(1) : encoded)
      .split(',')
      .map((value) => Number(value));
    if (
      valuesMm.length !== APPENDIX_A3_MAIN_BAR_COUNTS.length ||
      valuesMm.some((value) => !Number.isFinite(value) || value <= 0)
    ) {
      throw new TypeError(
        `Invalid Appendix A3 source values: ${tableId}:${mainBarDia}:${transverseBarDia}`,
      );
    }

    result[mainBarDia] ||= {};
    result[mainBarDia][transverseBarDia] = Object.freeze({
      valuesMm: Object.freeze(valuesMm),
      starredCoverRule,
    });
  }
  return Object.freeze(
    Object.fromEntries(
      Object.entries(result).map(([mainBarDia, rows]) => [mainBarDia, Object.freeze(rows)]),
    ),
  );
}

