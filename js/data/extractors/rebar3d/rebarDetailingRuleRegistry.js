const RULES_BY_ID = new Map();
for (const rule of RULES) {
  if (RULES_BY_ID.has(rule.id)) throw new TypeError(`Duplicate rebar rule id: ${rule.id}`);
  RULES_BY_ID.set(rule.id, rule);
}

export const REBAR_DETAILING_RULES = Object.freeze(RULES.slice());

export function getRebarDetailingRule(ruleId) {
  return RULES_BY_ID.get(String(ruleId || '')) || null;
}

export function listRebarDetailingRules({ memberType = null, autoApply = null } = {}) {
  return REBAR_DETAILING_RULES.filter((rule) => {
    if (memberType && rule.memberType !== String(memberType).toUpperCase()) return false;
    if (typeof autoApply === 'boolean' && rule.autoApply !== autoApply) return false;
    return true;
  });
}

export function rebarRuleTraceMetadata(ruleId) {
  const rule = getRebarDetailingRule(ruleId);
  if (!rule) throw new RangeError(`Unknown rebar detailing rule: ${ruleId}`);
  return Object.freeze({
    ruleId: rule.id,
    ruleType: rule.type,
    maturity: rule.maturity,
    precedence: rule.precedence,
    source: rule.source,
    normative: rule.normative,
    autoApply: rule.autoApply,
  });
}
