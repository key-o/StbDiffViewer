function freezeRule(rule) {
  if (!rule?.id) throw new TypeError('Rebar detailing rule requires id');
  if (!Object.values(RebarRuleType).includes(rule.type)) {
    throw new TypeError(`Unknown rebar rule type: ${rule.type}`);
  }
  if (!Object.values(RebarRuleMaturity).includes(rule.maturity)) {
    throw new TypeError(`Unknown rebar rule maturity: ${rule.maturity}`);
  }
  if (!Object.values(RebarRulePrecedence).includes(rule.precedence)) {
    throw new TypeError(`Unknown rebar rule precedence: ${rule.precedence}`);
  }
  const traceOnlyMaturity = [RebarRuleMaturity.EXPERIMENTAL, RebarRuleMaturity.HEURISTIC].includes(
    rule.maturity,
  );
  const normalized = {
    normative: false,
    phase: 'PHASE_1',
    ...rule,
    autoApply: typeof rule.autoApply === 'boolean' ? rule.autoApply : !traceOnlyMaturity,
  };
  if (traceOnlyMaturity && normalized.autoApply) {
    throw new TypeError(`${rule.maturity} rule must not auto apply: ${rule.id}`);
  }
  return Object.freeze(normalized);
}

